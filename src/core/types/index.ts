import type { Node as MorphNode } from "ts-morph";
import type { SourceFile, TypeChecker } from "ts-morph";

export type FileRole =
  | "guard"
  | "facade"
  | "store"
  | "context"
  | "service"
  | "component"
  | "page"
  | "hook"
  | "controller"
  | "repository"
  | "pipe"
  | "directive"
  | "routes"
  | "model"
  | "util"
  | "unknown";

export interface ExtractedContext extends Omit<
  SemanticContext,
  "title" | "meta" | "metrics" | "role" | "summary"
> {
  relatedContextFiles: string[];
}

export interface CPLintAdapter {
  name: string;
  classify(file: SourceFile): FileRole;
  extract(
    file: SourceFile,
    checker: TypeChecker,
    config: Config,
  ): ExtractedContext;
}

export type ManualBlockKey =
  | "purpose"
  | "decisions"
  | "constraints"
  | "known-pitfalls"
  | "not-in-scope"
  | "open-questions";

export type ManualDefaults = Record<ManualBlockKey, string>;

export type ManualBlocks = {
  [key in ManualBlockKey]?: string;
} & Record<string, string | undefined>;

export type ClassifierRule = {
  name?: string;
  kind?: string;
  label: string;
};

export type ImportRoleRule = {
  module?: string;
  label: string;
};

export type FlowBoundaryRule = {
  matchExpr?: string;
  matchFile?: string;
  label: string;
};

export type Config = {
  tsConfigFilePath: string;
  outputFileName: string;
  includePrivateTypes: boolean;
  maxTypeFields: number;
  maxFlowSteps: number;
  maxReferenceFiles: number;
  manualDefaults: ManualDefaults;
  classifiers: ClassifierRule[];
  importRoleRules: ImportRoleRule[];
  flowBoundaryRules: FlowBoundaryRule[];
  diagram?: boolean;
};

