export type EntryPoint = {
  name: string;
  kind: string;
  file: string;
};

/**
 * A single exported symbol in the public API.
 *
 * - `signature` — full call signature, e.g. `CardSectionTitle(title: string) → string`
 * - `flags`     — semantic tags inferred from the AST, e.g. ["exported", "pure", "async"]
 *
 * Replaces the old `kind | type` format which was ambiguous to LLMs.
 */
export type ApiSurfaceRow = {
  name: string;
  signature: string;
  flags: string[];
};

export type DependencyRow = {
  module: string;
  role: string;
  symbols: string[];
  type: string;
};

export type StateField = {
  name: string;
  type: string;
};

export type StateShapeRow = {
  name: string;
  fields: StateField[];
};

export type SemanticContext = {
  title: string;
  role: FileRole;
  /**
   * One-sentence AUTO summary of the file's primary export.
   * Generated by the AST — never edited manually.
   * Example: "Exported function component. Receives `title: string`, returns JSX. No side effects detected."
   */
  summary: string;
  meta: {
    generated: string;
    entry: string;
    related: string[];
  };
  entryPoints: EntryPoint[];
  apiSurface: ApiSurfaceRow[];
  deps: DependencyRow[];
  stateShape: StateShapeRow[];
  criticalFlow: string[];
  changeChecklist: string[];
};

export type ExportDeclRow = {
  exportName: string;
  decl: MorphNode;
};
